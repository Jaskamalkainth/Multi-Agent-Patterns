"""Write each step's graph as a Mermaid diagram to docs/graphs.md (paste into slides or GitHub)."""
import importlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
STEPS = ["step1_trigger", "step2_broken", "step3_owner", "step4_budget", "step5_approval"]

out = ["# Graphs for each step\n", "Generated by `python tools/draw_graphs.py`.\n"]
for name in STEPS:
    mod = importlib.import_module(f"steps.{name}")
    out += [f"\n## {mod.TITLE}\n", "```mermaid", mod.build().get_graph().draw_mermaid().strip(), "```"]
(ROOT / "docs").mkdir(exist_ok=True)
(ROOT / "docs" / "graphs.md").write_text("\n".join(out) + "\n")
print("Wrote docs/graphs.md")
